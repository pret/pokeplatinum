// NOTE: This will NOT be null terminated!
void CharCode_ToAsciiString(charcode_t * charcodeString, char * cString, int len)
{
    int outStringPos = 0;
    for(int i=0; i<len; i++) {
        char outChar = CharCodeToAsciiTable[charcodeString[i]];
        if(outChar) {
            cString[outStringPos] = outChar;
            outStringPos++;
        }
    }
}